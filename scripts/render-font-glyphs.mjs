import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import {createTMath,compileScene} from '../public/tmath/runtime/client.js';
import {buildGlyphs,verifyTrace} from '../public/tmath/font/glyphs.mjs';
import traces from '../public/tmath/font/native-trace.mjs';
import {buildDelegation} from '../public/tmath/font/delegation.mjs';
import {buildCurves} from '../public/tmath/font/curves.mjs';
import {verifyCurves} from '../public/tmath/font/curves-model.mjs';

const root=path.resolve(import.meta.dirname,'..'),output=path.join(root,'public/tmath/font');
const temp=path.join(output,'temp');
await fs.mkdir(temp,{recursive:true});
for (const trace of Object.values(traces)) verifyTrace(trace);
const still=process.argv.includes('--still');
const name=process.argv.includes('--curves')?'curves':process.argv.includes('--delegation')?'delegation':'glyphs';
if(name==='curves')verifyCurves();
const episode=({glyphs:buildGlyphs,delegation:buildDelegation,curves:buildCurves}[name])({still});
const source=`-- Generated by scripts/render-font-glyphs.mjs; edit ${name}.mjs.\nlocal refs = {}\n`+compileScene(episode.scene).replace(/^local (object\d+) = /gm,'$1 = ').replace(/\bobject(\d+)\b/g,'refs[$1]');
const runtime=await createTMath('return tmath.scene {}','bootstrap.lua',{renderEngine:'cpu',wasmBinary:await fs.readFile(path.join(root,'public/tmath/runtime/tmath-wasm.wasm'))});
const intersects=(a,b)=>a.x<b.x+b.width+4&&a.x+a.width+4>b.x&&a.y<b.y+b.height+4&&a.y+a.height+4>b.y;
try {
  runtime.font('Pretendard',await fs.readFile(path.join(root,'public/tmath/runtime/Pretendard.ttf')),'ttf');
  runtime.loadLua(source,`font-${name}.lua`);
  const [width,height]=runtime.size(),errors=new Set(),seen=new Set(),frames=Math.ceil(runtime.duration*30);
  for(let frame=0;frame<=frames;frame++) {
    const report=runtime.layoutReport(Math.min(frame/30,runtime.duration),4);
    const texts=report.objects.filter(o=>o.type==='text'&&o.visible&&o.paintBounds?.width>0);
    const objects=new Map(report.objects.map(o=>[o.id,o]));
    for(const t of texts) {
      const b=t.paintBounds,policy=episode.textPolicies[t.id];seen.add(t.id);
      if(!policy)errors.add('Missing policy: '+t.id);
      if(b.x<4||b.y<4||b.x+b.width>width-4||b.y+b.height>height-4||t.clipped)errors.add('Clipped text: '+t.id);
      if(policy?.owner) {
        const owner=objects.get(policy.owner)?.paintBounds,n=policy.inset;
        if(!owner||b.x<owner.x+n||b.y<owner.y+n||b.x+b.width>owner.x+owner.width-n||b.y+b.height>owner.y+owner.height-n)errors.add('Containment: '+t.id);
      }
    }
    for(let a=0;a<texts.length;a++)for(let b=a+1;b<texts.length;b++)if(intersects(texts[a].paintBounds,texts[b].paintBounds))errors.add('Text overlap: '+texts[a].id+' / '+texts[b].id);
  }
  for(const key of episode.textIds)if(!seen.has(key))errors.add('Never visible: '+key);
  const times=[...new Set([0,...episode.beats.map(b=>b.time),runtime.duration])];
  for(const [index,time] of times.entries())await sharp(Buffer.from(runtime.render(time,true)),{raw:{width,height,channels:4}}).png().toFile(path.join(temp,`${name}-${still?'still-':''}${index}.png`));
  const summary={width,height,duration:runtime.duration,frames:frames+1,errors:[...errors],beats:episode.beats,commits:episode.commits,reviewTimes:times};
  await fs.writeFile(path.join(temp,`${name}-audit.json`),JSON.stringify(summary,null,2));
  console.log(JSON.stringify(summary));
  if(errors.size)process.exitCode=1;
  else if(!still) {
    await fs.writeFile(path.join(output,`${name}.lua`),source);
    await sharp(Buffer.from(runtime.render(runtime.duration,true)),{raw:{width,height,channels:4}}).webp({quality:94}).toFile(path.join(output,`${name}.webp`));
  }
} finally {runtime.destroy();}
