import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';

const root=path.resolve(import.meta.dirname,'..');
const sourceCommit='4d5810cf6f8d1c62dff4d9d3d291d3c2984074ad';
assert.equal(execFileSync('git',['-C',path.join(root,'thorvg'),'rev-parse','HEAD'],{encoding:'utf8'}).trim(),sourceCommit);
const build=process.env.THORVG_BUILD||'/tmp/thorvg-cpu-4d5810cf-build';
const review=fs.mkdtempSync(path.join(os.tmpdir(),'update-prepare-native-'));
for(const kind of ['image','bitmap','fill']){
 const binary=path.join(review,kind);
 execFileSync('c++',['-std=c++17','-O2','-fno-access-control','-DTVG_STATIC',...['', 'inc','src/common','src/renderer','src/renderer/cpu_engine'].filter(Boolean).map(p=>'-I'+path.join(root,'thorvg',p)),'-I'+build,path.join(root,`scripts/update-${kind}-native-trace.cpp`),path.join(build,'src/libthorvg-1.a'),'-lpthread','-o',binary],{stdio:'inherit'});
 const [baseline,variant]=[[],['translated']].map(args=>JSON.parse(execFileSync(binary,args,{encoding:'utf8'})));
 const records=kind==='bitmap'?[...baseline,...variant]:[baseline,variant];
 for(const record of records){if(kind==='fill')assert.equal(record.opaque,true);else{assert.equal(record.canvasUntouched,true);assert.equal(record[kind==='bitmap'?'sourceAlias':'publicApiMatch'],true);}}
 fs.writeFileSync(path.join(root,`public/tmath/update/${kind}-native.mjs`),`// Generated by scripts/generate-update-prepare-trace.mjs; native public Update + task->done().\nexport const sourceCommit=${JSON.stringify(sourceCommit)};\nexport const variant=${JSON.stringify(variant)};\nexport default ${JSON.stringify(baseline,null,2)};\n`);
}
console.log(`Native Image/Bitmap/Fill baseline and asymmetric fixtures verified; review binaries: ${review}`);
