import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {writeFile} from 'node:fs/promises';
import {SOURCE_COMMIT,traceDirect,traceScaled,traceTexmap,traceSolid,traceGradient,traceStroke,traceComposition,sampleNearest,sampleBilinear,sampleDownscale,alphaBlend,interpolate,sourceOver} from '../public/tmath/raster/model.mjs';

const binary=process.argv[2];
if(!binary)throw new Error('Pass the compiled raster-native-trace executable; see public/tmath/raster/README.md.');
assert.equal(execFileSync('git',['-C','thorvg','rev-parse','HEAD'],{encoding:'utf8'}).trim(),SOURCE_COMMIT);
const run=args=>JSON.parse(execFileSync(binary,args,{encoding:'utf8',maxBuffer:8*1024*1024}));
const baseline=run([]),variant=run(['variant']);
for(const native of [baseline,variant]) {
  assert.equal(native.sourceCommit,SOURCE_COMMIT);
  const image={width:6,height:6,pixels:native.source};
  const traces={direct:traceDirect(image),nearest:traceScaled(image,{filter:'Nearest'}),bilinear:traceScaled(image),downscale:traceScaled(image,{scale:.25,id:'downscale'}),texmap:traceTexmap(image),solidRect:traceSolid({rle:false,fixture:native.solidRect}),solidRle:traceSolid({fixture:native.solidRle}),composition:traceComposition(image),gradientRect:traceGradient({rle:false,fixture:native.gradientRect}),gradientRle:traceGradient({fixture:native.gradientRle}),strokeSolid:traceStroke({fixture:native.strokeSolid}),strokeGradient:traceStroke({gradient:true,fixture:native.strokeGradient})};
  for(const [name,trace] of Object.entries(traces))assert.deepEqual(trace.target.pixels,native[name].pixels,name);
  for(const s of native.samples) {
    assert.deepEqual(sampleNearest(image,s.sx,s.sy).rgba,s.nearest[0]);
    assert.deepEqual(sampleBilinear(image,s.sx,s.sy).rgba,s.bilinear[0]);
  }
  for(const s of native.downsamples)assert.deepEqual(sampleDownscale(image,s.sx,s.sy,s.scale).rgba,s.rgba[0]);
  for(const c of native.byteCases) {
    assert.deepEqual(alphaBlend(c.src[0],c.opacity),c.alphaBlend[0]);
    assert.deepEqual(interpolate(c.src[0],c.dst[0],c.opacity),c.interpolate[0]);
    assert.deepEqual(sourceOver(c.src[0],c.dst[0],c.opacity).rgba,c.sourceOver[0]);
  }
}
for(const name of ['direct','nearest','bilinear','downscale','texmap','solidRle','composition','gradientRect','gradientRle','strokeSolid','strokeGradient'])assert.notDeepEqual(baseline[name].pixels,variant[name].pixels,name+' must react to changed input');
assert.notDeepEqual(baseline.solidRle.spans,variant.solidRle.spans);
await writeFile(new URL('../public/tmath/raster/native-trace.mjs',import.meta.url),'// Generated by scripts/generate-raster-trace.mjs from unmodified pinned ThorVG.\nexport default '+JSON.stringify(baseline)+';\nexport const variant='+JSON.stringify(variant)+';\n');
console.log('All 12 raster paths match native bytes for baseline and perturbed bitmap/geometry/gradient; 416 native helper results match.');
