import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import {createTMath, compileScene} from '../public/tmath/runtime/client.js';

const root = path.resolve(import.meta.dirname, '..');
const output = path.join(root, 'public/tmath/postprocessing/details');
const temp = path.join(output, 'temp');
const bundle = path.join(root, 'public/tmath/runtime');
await fs.mkdir(temp, {recursive: true});
const runtime = await createTMath('return tmath.scene {}', 'bootstrap.lua', {
  renderEngine: 'cpu', wasmBinary: await fs.readFile(path.join(bundle, 'tmath-wasm.wasm')),
});
runtime.font('Pretendard', await fs.readFile(path.join(bundle, 'Pretendard.ttf')), 'ttf');
const builders = {
  blur: ['effect-blur.mjs', 'buildBlurDetail'],
  tint: ['effect-colors.mjs', 'buildTintDetail'],
  tritone: ['effect-colors.mjs', 'buildTritoneDetail'],
  fill: ['effect-colors.mjs', 'buildFillDetail'],
  shadow: ['effect-shadow.mjs', 'buildShadowDetail'],
  'alpha-internal': ['alpha-internal.mjs', 'buildAlphaInternal'],
};
const ids = process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(builders);
const overlap = (a,b,gap=4) => a.x < b.x+b.width+gap && a.x+a.width+gap > b.x && a.y < b.y+b.height+gap && a.y+a.height+gap > b.y;
try {
  for (const id of ids) {
    if (!builders[id]) throw new Error('Unknown effect: ' + id);
    const [file, name] = builders[id];
    const episode = (await import('../public/tmath/postprocessing/' + file))[name]();
    // Raster's typed authoring workflow emits playable, standalone Lua. Table-backed
    // handles avoid Lua's 200-local limit for thousands of individual pixel writes.
    const source = '-- Generated by scripts/render-effect-details.mjs; edit ' + file + '.\nlocal refs = {}\n' + compileScene(episode.scene)
      .replace(/^local (object\d+) = /gm, '$1 = ').replace(/\bobject(\d+)\b/g, 'refs[$1]');
    await fs.writeFile(path.join(output, id + '.lua'), source);
    runtime.loadLua(source, id + '.lua');
    const [width,height] = runtime.size();
    const errors = new Set(), seen = new Set();
    const frames = Math.ceil(runtime.duration * 30);
    for (let f = 0; f <= frames; f++) {
      const report = runtime.layoutReport(Math.min(f / 30, runtime.duration), 4);
      const texts = report.objects.filter(o => o.type === 'text' && o.visible && o.paintBounds?.width > 0);
      const objects = new Map(report.objects.map(o => [o.id,o]));
      for (const t of texts) {
        const b = t.paintBounds, policy = episode.textPolicies[t.id]; seen.add(t.id);
        if (!policy) errors.add('Missing policy: ' + t.id);
        if (b.x < 4 || b.y < 4 || b.x+b.width > width-4 || b.y+b.height > height-4 || t.clipped)
          errors.add('Clipped text: ' + t.id);
        if (policy?.owner) {
          const owner = objects.get(policy.owner)?.paintBounds, inset = policy.inset;
          if (!owner || b.x < owner.x+inset || b.y < owner.y+inset || b.x+b.width > owner.x+owner.width-inset || b.y+b.height > owner.y+owner.height-inset)
            errors.add('Containment: ' + t.id);
        }
      }
      for (let a = 0; a < texts.length; a++) for (let b = a+1; b < texts.length; b++) {
        if (overlap(texts[a].paintBounds,texts[b].paintBounds)) errors.add('Text overlap: ' + texts[a].id + ' / ' + texts[b].id);
      }
    }
    for (const id of episode.textIds) if (!seen.has(id)) errors.add('Never visible: ' + id);
    const times = [...new Set([0,...episode.beats.map(b=>Math.min(b.time,runtime.duration)),runtime.duration])];
    let finalPixels;
    for (const [index,time] of times.entries()) {
      const pixels = Buffer.from(runtime.render(time,true));
      if (time === runtime.duration) finalPixels = pixels;
      await sharp(pixels,{raw:{width,height,channels:4}}).png().toFile(path.join(temp, `${id}-${index}.png`));
    }
    if (!finalPixels) throw new Error('Missing reviewed final frame: ' + id);
    await sharp(finalPixels,{raw:{width,height,channels:4}}).webp({quality:95})
      .toFile(path.join(root,'public/tmath/postprocessing/posters',id+'.webp'));
    const summary = {id,width,height,duration:runtime.duration,frames:frames+1,texts:seen.size,errors:[...errors],beats:episode.beats,reviewTimes:times};
    await fs.writeFile(path.join(temp,id+'.audit.json'),JSON.stringify(summary,null,2));
    console.log(JSON.stringify(summary));
    if (errors.size) process.exitCode = 1;
  }
} finally {runtime.destroy();}
