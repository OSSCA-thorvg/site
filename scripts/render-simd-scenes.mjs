import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import sharp from 'sharp';
import {createTMath,compileScene} from '../public/tmath/runtime/client.js';

const root=path.resolve(import.meta.dirname,'..'),output=path.join(root,'public/tmath/simd');
const temp=process.env.TMATH_SIMD_REVIEW_DIR || path.join(os.tmpdir(),'thorvg-simd-review');
await fs.mkdir(temp,{recursive:true});await fs.mkdir(path.join(output,'posters'),{recursive:true});
const builders={downscale:['scenes.mjs','buildDownscale'],neon:['scenes.mjs','buildNeon']};
const ids=process.argv.slice(2).length?process.argv.slice(2):Object.keys(builders);
const runtime=await createTMath('return tmath.scene {}','bootstrap.lua',{renderEngine:'cpu',wasmBinary:await fs.readFile(path.join(root,'public/tmath/runtime/tmath-wasm.wasm'))});
runtime.font('Pretendard',await fs.readFile(path.join(root,'public/tmath/runtime/Pretendard.ttf')),'ttf');
const intersects=(a,b,gap=4)=>a.x<b.x+b.width+gap&&a.x+a.width+gap>b.x&&a.y<b.y+b.height+gap&&a.y+a.height+gap>b.y;
try {
 for(const id of ids){
  const [file,name]=builders[id];const episode=(await import(path.join(output,file)))[name]();
  const source='-- Generated by scripts/render-simd-scenes.mjs; edit '+file+'.\nlocal refs = {}\n'+compileScene(episode.scene).replace(/^local (object\d+) = /gm,'$1 = ').replace(/\bobject(\d+)\b/g,'refs[$1]');
  runtime.loadLua(source,id+'.lua');
  const [width,height]=runtime.size(),errors=new Set(),seen=new Set(),frames=Math.ceil(runtime.duration*30);
  for(let frame=0;frame<=frames;frame++){
   const time=Math.min(frame/30,runtime.duration),report=runtime.layoutReport(time,4);
   const texts=report.objects.filter(o=>o.type==='text'&&o.visible&&o.paintBounds?.width>0),objects=new Map(report.objects.map(o=>[o.id,o]));
   for(const t of texts){
    const b=t.paintBounds,policy=episode.textPolicies[t.id];seen.add(t.id);
    if(!policy)errors.add('Missing policy: '+t.id);
    if(b.x<4||b.y<4||b.x+b.width>width-4||b.y+b.height>height-4||t.clipped)errors.add('Clipped text: '+t.id);
    if(policy?.owner){const owner=objects.get(policy.owner)?.paintBounds,n=policy.inset??12;if(!owner||b.x<owner.x+n||b.y<owner.y+n||b.x+b.width>owner.x+owner.width-n||b.y+b.height>owner.y+owner.height-n)errors.add('Containment: '+t.id);}
   }
   for(let a=0;a<texts.length;a++)for(let b=a+1;b<texts.length;b++)if(intersects(texts[a].paintBounds,texts[b].paintBounds))errors.add('Text overlap: '+texts[a].id+' / '+texts[b].id);
  }
  for(const key of episode.textIds)if(!seen.has(key))errors.add('Never visible: '+key);
  const times=[...new Set([0,...episode.beats.map(b=>Math.min(b.time,runtime.duration)),runtime.duration])];
  for(const [index,time] of times.entries())await sharp(Buffer.from(runtime.render(time,true)),{raw:{width,height,channels:4}}).png().toFile(path.join(temp,`${id}-${index}.png`));
  const summary={id,width,height,duration:runtime.duration,frames:frames+1,errors:[...errors],beats:episode.beats,reviewTimes:times};
  await fs.writeFile(path.join(temp,id+'.audit.json'),JSON.stringify(summary,null,2));
  if(!errors.size){await fs.writeFile(path.join(output,id+'.lua'),source);await sharp(Buffer.from(runtime.render(runtime.duration,true)),{raw:{width,height,channels:4}}).webp({quality:94}).toFile(path.join(output,'posters',id+'.webp'));}
  console.log(JSON.stringify(summary));if(errors.size)process.exitCode=1;
 }
}finally{runtime.destroy();}
