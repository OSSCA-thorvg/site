import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {writeFile} from 'node:fs/promises';
import {buildColorTrace, configs, tritoneMap} from '../public/tmath/postprocessing/effect-colors-model.mjs';
import {trace} from '../public/tmath/postprocessing/native-evidence.mjs';

const binary = process.argv[2];
if (!binary) throw new Error('Pass the compiled scripts/effect-colors-native.cpp executable.');
const run = args => JSON.parse(execFileSync(binary, args, {encoding:'utf8', maxBuffer:8*1024*1024}));
const baseline = run([]), perturbed = run(['perturbed']);
for (const samples of [baseline, perturbed]) for (const sample of samples) {
  const model = buildColorTrace(sample.id, {input:sample.input, opacity:sample.opacity, parameter:sample.parameter, bbox:sample.bbox});
  assert.deepEqual(model.output, sample.output, sample.id + ' native effect output');
  assert.ok(sample.verifiedCanvasMatch && sample.verifiedInPlace && sample.verifiedParentDeferred);
  let replay = [...model.input];
  for (const step of model.steps) {
    assert.equal(replay[step.index], model.input[step.index], 'read before same-slot write');
    replay[step.index] = model.output[step.index];
  }
  assert.deepEqual(replay, sample.output);
}
for (const sample of baseline) {
  assert.deepEqual(sample.input, trace.filtered);
  assert.notDeepEqual(sample.output, perturbed.find(p => p.id === sample.id).output);
}
assert.deepEqual(baseline.find(s => s.id === 'fill').output, trace.compositionInput);
const varied = perturbed.find(s => s.id === 'tritone');
assert.ok(buildColorTrace('tritone', {input:varied.input}).steps.some(s => !s.lower), 'asymmetric native sample exercises highlight branch');
assert.equal(tritoneMap(127).lower, true); assert.equal(tritoneMap(128).lower, false);
assert.deepEqual(tritoneMap(0).mapped, configs.tritone.shadow);
await writeFile(new URL('../public/tmath/postprocessing/effect-colors-native.mjs', import.meta.url),
  '// Generated by scripts/effect-colors-verify.mjs; unmodified b4471844 native CPU engine.\nexport default ' + JSON.stringify({sourceCommit:trace.sourceCommit, baseline, perturbed}) + ';\n');
console.log('3 color chains × 2 asymmetric variants: every stored output byte matches native; all final Canvas pixels match public draw().');
