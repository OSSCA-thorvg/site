import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {writeFile} from 'node:fs/promises';

assert.equal(execFileSync('git', ['-C', 'thorvg', 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim(), '4d5810cf6f8d1c62dff4d9d3d291d3c2984074ad');
const binary = process.argv[2];
if (!binary) throw new Error('Pass the effect-shadow-native-trace executable.');
const run = args => JSON.parse(execFileSync(binary, args, {encoding: 'utf8', maxBuffer: 8 * 1024 * 1024}));
const trace = run([]), variant = run(['perturbed']);
for (const data of [trace, variant]) {
  assert.ok(data.direct && data.verifiedBlurReplay && data.verifiedShiftReplay);
  assert.ok(data.verifiedOriginalRestored && data.verifiedCanvasMatch);
  assert.equal(data.temporaryBuffers, 3);
  assert.equal(data.passes.length, 8);
}
assert.notDeepEqual(trace.offset, variant.offset);
assert.notDeepEqual(trace.original, variant.original);
assert.notDeepEqual(trace.final, variant.final);
trace.sourceCommit = variant.sourceCommit = '4d5810cf6f8d1c62dff4d9d3d291d3c2984074ad';
await writeFile(new URL('../public/tmath/postprocessing/effect-shadow-trace.mjs', import.meta.url),
  '// Generated by scripts/effect-shadow-generate-trace.mjs from the unmodified ThorVG CPU engine.\n' +
  'export const variant = ' + JSON.stringify(variant) + ';\nexport default ' + JSON.stringify(trace) + ';\n');
console.log('DropShadow: eight native passes, offset writes, original restore and public Canvas match; changed angle/shape verified.');
