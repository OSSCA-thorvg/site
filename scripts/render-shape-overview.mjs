import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import {createTMath,compileScene} from '../public/tmath/runtime/client.js';
import {buildShapeOverview,shapeModel} from '../public/tmath/shape/overview.mjs';
import trace,{variant} from '../public/tmath/shape/native-trace.mjs';

const root=path.resolve(import.meta.dirname,'..'),output=path.join(root,'public/tmath/shape');
const alternate=process.argv.includes('--variant');
const temp=path.join(output,'temp',alternate?'variant':'baseline');
await fs.mkdir(temp,{recursive:true});
const still=process.argv.includes('--still');
shapeModel(variant);
const fixture=alternate?variant:trace;
const episode=buildShapeOverview(fixture,{still});
const source='-- Generated by scripts/render-shape-overview.mjs; edit overview.mjs.\nlocal refs = {}\n'+compileScene(episode.scene).replace(/^local (object\d+) = /gm,'$1 = ').replace(/\bobject(\d+)\b/g,'refs[$1]');
const runtime=await createTMath('return tmath.scene {}','bootstrap.lua',{renderEngine:'cpu',wasmBinary:await fs.readFile(path.join(root,'public/tmath/runtime/tmath-wasm.wasm'))});
const intersects=(a,b)=>a.x<b.x+b.width+4&&a.x+a.width+4>b.x&&a.y<b.y+b.height+4&&a.y+a.height+4>b.y;
try {
  runtime.font('Pretendard',await fs.readFile(path.join(root,'public/tmath/runtime/Pretendard.ttf')),'ttf');
  runtime.loadLua(source,'shape-overview.lua');
  const [width,height]=runtime.size(),errors=new Set(),seen=new Set(),frames=Math.ceil(runtime.duration*30);
  for(let frame=0;frame<=frames;frame++) {
    const report=runtime.layoutReport(Math.min(frame/30,runtime.duration),4);
    const texts=report.objects.filter(o=>o.type==='text'&&o.visible&&o.paintBounds?.width>0);
    const objects=new Map(report.objects.map(o=>[o.id,o]));
    for(const t of texts) {
      const b=t.paintBounds,policy=episode.textPolicies[t.id];seen.add(t.id);
      if(!policy)errors.add('Missing policy: '+t.id);
      if(b.x<4||b.y<4||b.x+b.width>width-4||b.y+b.height>height-4||t.clipped)errors.add('Clipped text: '+t.id);
      if(policy?.owner) {
        const owner=objects.get(policy.owner)?.paintBounds,n=policy.inset;
        if(!owner||b.x<owner.x+n||b.y<owner.y+n||b.x+b.width>owner.x+owner.width-n||b.y+b.height>owner.y+owner.height-n)errors.add('Containment: '+t.id);
      }
    }
    for(let a=0;a<texts.length;a++)for(let b=a+1;b<texts.length;b++)if(intersects(texts[a].paintBounds,texts[b].paintBounds))errors.add('Text overlap: '+texts[a].id+' / '+texts[b].id);
  }
  if(!still)for(const key of episode.textIds)if(!seen.has(key))errors.add('Never visible: '+key);
  const finalPixels=Buffer.from(runtime.render(runtime.duration,true));
  let pixelChecks=0,geometryChecks=0;
  for(const gridName of ['surface','coverage'])for(let y=0;y<fixture.h;y++)for(let x=0;x<fixture.w;x++){
    const g=episode.grids[gridName],offset=(Math.floor(g.y+(y+.5)*g.u)*width+Math.floor(g.x+(x+.5)*g.u))*4;
    const value=fixture.pixels[y*fixture.stride+x];
    const wanted=gridName==='surface'?[value&255,value>>>8&255,value>>>16&255]:Array(3).fill(255-episode.model.coverage[y*fixture.w+x]);
    if(wanted.some((v,j)=>Math.abs(v-finalPixels[offset+j])>1))errors.add(`Pixel ${gridName} ${x},${y}`);
    pixelChecks++;
  }
  const finalObjects=new Map(runtime.layoutReport(runtime.duration,4).objects.map(o=>[o.id,o]));
  for(const check of episode.spanLines){
    const b=finalObjects.get(check.id)?.paintBounds;
    if(!b||Math.abs(b.x-(check.start[0]-1))>1.1||Math.abs(b.y-(check.start[1]-1))>1.1||Math.abs(b.width-(check.end[0]-check.start[0]+2))>1.1)errors.add('Span geometry: '+check.id);
    geometryChecks++;
  }
  const times=[...new Set([0,...episode.beats.map(b=>b.time),runtime.duration])];
  for(const [index,time] of times.entries())await sharp(Buffer.from(runtime.render(time,true)),{raw:{width,height,channels:4}}).png().toFile(path.join(temp,`overview-${index}.png`));
  const summary={width,height,duration:runtime.duration,frames:frames+1,pixelChecks,geometryChecks,errors:[...errors],beats:episode.beats,reviewTimes:times};
  await fs.writeFile(path.join(temp,'audit.json'),JSON.stringify(summary,null,2));
  console.log(JSON.stringify(summary));
  if(errors.size)process.exitCode=1;
  else if(!still&&!alternate) {
    await fs.writeFile(path.join(output,'overview.lua'),source);
    await sharp(Buffer.from(runtime.render(runtime.duration,true)),{raw:{width,height,channels:4}}).webp({quality:94}).toFile(path.join(output,'overview.webp'));
  }
} finally {runtime.destroy();}
