import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import regions,{variant as shifted,commit} from '../public/tmath/cpu-regions/native-trace.mjs';
const root=path.resolve(import.meta.dirname,'..'),src=path.join(root,'thorvg');
assert.equal(execFileSync('git',['-C',src,'rev-parse','HEAD'],{encoding:'utf8'}).trim(),commit);
const build=process.env.THORVG_BUILD;assert(build,'THORVG_BUILD must identify a matching scalar static CPU build');
const temp=await fs.mkdtemp(path.join(os.tmpdir(),'mask-pixels-native-')),binary=path.join(temp,'probe');
const fixture=await fs.readFile(path.join(root,'scripts/cpu-regions-native.cpp'),'utf8');
assert.equal(fixture.split('int main(').length,2);
await fs.writeFile(path.join(temp,'mask-avatar-fixture.h'),fixture.slice(0,fixture.indexOf('int main(')));
execFileSync('c++',['-std=c++17','-O2','-ffp-contract=off','-fno-access-control','-I'+build,'-I'+temp,...['inc','src/common','src/renderer','src/renderer/cpu_engine'].map(p=>'-I'+path.join(src,p)),path.join(root,'scripts/mask-pixels-native.cpp'),path.join(build,'src/libthorvg-1.a'),'-lpthread','-o',binary],{stdio:'inherit'});
const native=JSON.parse(execFileSync(binary,[],{encoding:'utf8'})),variant=JSON.parse(execFileSync(binary,['variant'],{encoding:'utf8'}));
for(const [r,n] of [[regions,native],[shifted,variant]]){
 for(const key of ['maskCoverage','maskSpans','badgeCoverage','badgeSpans','maskStorage','groupPixels','pixels'])assert.deepEqual(n.transparent[key],r.maskAvatar[key],key);
 for(const key of ['maskStorage','groupPixels'])assert.deepEqual(n.transparent[key],n.background[key],key);
 assert.notDeepEqual(n.transparent.pixels,n.background.pixels);
}
const output=path.join(root,'public/tmath/mask-pixels');await fs.mkdir(output,{recursive:true});
await fs.writeFile(path.join(output,'native-trace.mjs'),`// Generated by scripts/generate-mask-pixels-trace.mjs.\nexport const commit='${commit}';\nexport default ${JSON.stringify(native)};\nexport const variant=${JSON.stringify(variant)};\n`);
console.log({commit,temp,pixels:native.transparent.pixels.length,destinations:2,fixtures:2});
