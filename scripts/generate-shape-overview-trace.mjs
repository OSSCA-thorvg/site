import fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';

const root = path.resolve(import.meta.dirname, '..');
const source = path.resolve(process.env.THORVG_SOURCE || path.join(root, 'thorvg'));
const build = process.env.THORVG_BUILD;
if (!build) throw new Error('THORVG_BUILD must point to a matching static ThorVG build.');
const temp = path.join(root, 'public/tmath/shape/temp/native');
await fs.mkdir(temp, {recursive: true});
let cpp = await fs.readFile(path.join(source, 'src/renderer/cpu_engine/tvgSwRle.cpp'), 'utf8');
function insert(anchor, replacement) {
  assert.equal(cpp.split(anchor).length, 2, `Unique native anchor: ${anchor}`);
  cpp = cpp.replace(anchor, replacement);
}
insert('static inline SwPoint UPSCALE', `
struct TraceEvent {int kind; long a, b, c, d;};
struct TraceBand {int lo, hi; bool ok = false; std::vector<TraceEvent> events, cells;};
static bool capture = false;
static std::vector<TraceBand> recorded;
static void finishTrace(RleWorker& rw) {
    if (!capture) return;
    auto& band = recorded.back(); band.ok = true;
    for (int y = 0; y < rw.yCnt; ++y) for (auto c = rw.yCells[y]; c; c = c->next)
        band.cells.push_back({1,c->x + rw.cellMin.x,y + rw.cellMin.y,c->cover,c->area});
}
static inline SwPoint UPSCALE`);
insert('cell->cover += rw.cover;', `cell->cover += rw.cover;
        if (capture) recorded.back().events.push_back({1,cell->x + rw.cellMin.x,rw.cellPos.y + rw.cellMin.y,cell->cover,cell->area});`);
insert('static bool _lineTo(RleWorker& rw, const SwPoint& to)\n{', `static bool _lineTo(RleWorker& rw, const SwPoint& to)
{
    if (capture) recorded.back().events.push_back({0,rw.pos.x,rw.pos.y,to.x,to.y});`);
insert('static bool _genRle(RleWorker& rw)\n{', `static bool _genRle(RleWorker& rw)
{
    if (capture) recorded.push_back({rw.cellMin.y,rw.cellMax.y});`);
insert('_sweep(rw);\n                --band;', '_sweep(rw);\n                finishTrace(rw);\n                --band;');
await fs.writeFile(path.join(temp, 'shape-rle-instrumented.cpp'), cpp);
const binary = path.join(temp, 'trace');
execFileSync('c++', ['-std=c++17', '-O2', '-DTVG_STATIC', '-I'+build, '-I'+temp,
  ...['inc','src','src/common','src/renderer','src/renderer/cpu_engine'].map(p=>'-I'+path.join(source,p)),
  path.join(root,'scripts/shape-overview-native.cpp'),path.join(build,'src/libthorvg-1.a'),'-o',binary], {stdio:'inherit'});
const trace = JSON.parse(execFileSync(binary, {encoding:'utf8'}));
const variant = JSON.parse(execFileSync(binary, ['shift'], {encoding:'utf8'}));
assert.notDeepEqual(trace.spans, variant.spans);
assert.ok(trace.bands.some(b=>!b.ok));
assert.ok(trace.bands.filter(b=>b.ok).length > 1);
trace.sourceCommit = execFileSync('git',['-C',source,'rev-parse','HEAD'],{encoding:'utf8'}).trim();
await fs.writeFile(path.join(root,'public/tmath/shape/native-trace.mjs'),
  '// Generated by scripts/generate-shape-overview-trace.mjs.\nexport const variant = '+JSON.stringify(variant)+';\nexport default '+JSON.stringify(trace)+';\n');
console.log(JSON.stringify({bands:trace.bands.map(b=>[b.lo,b.hi,b.ok]), spans:trace.spans.length, commit:trace.sourceCommit}));
