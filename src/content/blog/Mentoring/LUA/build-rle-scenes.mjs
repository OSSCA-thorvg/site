import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const dir=path.dirname(fileURLToPath(import.meta.url));
const trace=JSON.parse(await fs.readFile(path.join(dir,'rle-engine-trace.txt'),'utf8'));
const lua=v=>Array.isArray(v)?'{'+v.map(lua).join(',')+'}':v&&typeof v==='object'?'{'+Object.entries(v).map(([k,v])=>`${k}=${lua(v)}`).join(',')+'}':JSON.stringify(v);
const common=`-- Actual ThorVG 6cf10d4 output, generated by rle-engine-trace.cpp.
-- CPU / SIMD off / threads off / opaque solid fill / Normal / ABGR8888.
-- Every span and packed output pixel comes from unmodified rasterShape().
-- Per-span replay was byte-for-byte equal to public SwCanvas draw(false).
-- Not an instruction timing trace: each animation beat replays one completed span.
-- Text ownership: label_* standalone; cell backgrounds contain no Text.
-- Bands: buffer/grid 10/20, span geometry 30, cursor 40, labels 60.
-- BEGIN ENGINE TRACE
local trace=${lua(trace)}
-- END ENGINE TRACE
local W,H=2400,1400
local scene=tmath.scene{width=W,height=H,fps=30,loop=false,theme="pro_white",camera={mode="fixed",view="2d",height=H}}
local function p(x,y) return {x-W/2,H/2-y} end
local function rgb(v) return string.format("#%02x%02x%02x",v%256,math.floor(v/256)%256,math.floor(v/65536)%256) end
local function gray(c) local v=255-math.floor(c*195/255);return string.format("#%02x%02x%02x",v,v,v) end
local function label(owner,id,value,x,y,size)
 return owner:text{id="label_"..id,text=value,point=p(x,y),font="Pretendard",role="text",size=size or 26,align={0,0.5},fill="#344158",layer=60}
end
local function rect(owner,id,x,y,w,h,fill,stroke,layer)
 return owner:rectangle{id=id,center=p(x,y),size={w,h},fill=fill,stroke=stroke or "#00000000",width=1.2,layer=layer or 20}
end
local function spanGlyph(owner,id,s,x,y,unit)
 local bx=x+(s.x+0.5)*unit;local by=y+(s.y+0.5)*unit;local ex=bx+s.len*unit
 local mark=rect(owner,id.."_begin",bx,by,unit*.36,unit*.36,gray(s.coverage),nil,30)
 local line=owner:line{id=id.."_length",from=p(bx,by),to=p(ex,by),stroke=gray(s.coverage),width=2.5,layer=30}
 owner:line{id=id.."_end",from=p(ex,by-5),to=p(ex,by+5),stroke=gray(s.coverage),width=2,layer=30}
 return line
end
local columns={140,270,400,530,700}
local tableTop,rowH,pageSize=280,60,10
local function spanTable(hidden)
 label(scene,"array","SwRle.spans ("..#trace.spans..")",140,100,34)
 for i,v in ipairs({"i","x","y","len","coverage"}) do label(scene,"field_"..i,v,columns[i],220,24) end
 local rows={}
 for i,s in ipairs(trace.spans) do
  local g=scene:group{id="span_record_"..i,opacity=(hidden or i>pageSize) and 0 or 1};rows[i]=g
  for j,v in ipairs({i-1,s.x,s.y,s.len,s.coverage}) do label(g,"row_"..i.."_"..j,tostring(v),columns[j],tableTop+((i-1)%pageSize)*rowH,30) end
 end
 return rows
end
`;
const creation=`-- Beats: path -> prepared span array -> spatial start/length correspondence.
local x0,y0,unit=1240,370,64
local rows=spanTable(true)
label(scene,"outline","SwOutline → SwSpan",1240,100,32)
local points={};for _,v in ipairs(trace.polygon) do points[#points+1]=p(x0+v[1]*unit,y0+v[2]*unit) end
local outline=scene:polygon{id="outline",points=points,fill="#2078dc08",stroke="#2078dc",width=2.5,layer=25}
for x=0,trace.w do scene:line{id="grid_x_"..x,from=p(x0+x*unit,y0),to=p(x0+x*unit,y0+trace.h*unit),stroke="#e2e7ed",width=1,layer=10} end
for y=0,trace.h do scene:line{id="grid_y_"..y,from=p(x0,y0+y*unit),to=p(x0+trace.w*unit,y0+y*unit),stroke="#e2e7ed",width=1,layer=10} end
local glyphs,lines,focus={},{},{}
for i,s in ipairs(trace.spans) do
 glyphs[i]=scene:group{id="span_"..i,opacity=0}
 lines[i]=spanGlyph(glyphs[i],"span_"..i,s,x0,y0,unit)
 focus[i]=rect(scene,"record_focus_"..i,510,tableTop+((i-1)%pageSize)*rowH,820,rowH-1,"#00000000","#ce8c31",40)
end
-- Length legend is derived from an actual fully covered run.
local example
for _,s in ipairs(trace.spans) do if s.coverage==255 and (not example or s.len>example.len) then example=s end end
local lx,ly=1330,1110
local bx=lx;local ex=lx+example.len*unit
rect(scene,"legend_begin",bx,ly,24,24,gray(example.coverage),nil,30)
scene:line{id="legend_length",from=p(bx,ly),to=p(ex,ly),stroke=gray(example.coverage),width=2.5,layer=30}
scene:line{id="legend_end",from=p(ex,ly-6),to=p(ex,ly+6),stroke=gray(example.coverage),width=2,layer=30}
label(scene,"begin","begin = "..example.x,bx-50,ly+65,24)
label(scene,"end","end = "..(example.x+example.len),ex-40,ly+65,24)
label(scene,"len","len = "..example.len,bx+(ex-bx)/2-50,ly-55,26)
scene:wait(0.6)
scene:create(outline,0.9)
for i,s in ipairs(trace.spans) do
 if i>1 and (i-1)%pageSize==0 then
  local hide={};for j=i-pageSize,i-1 do hide[#hide+1]={target=rows[j],opacity=0} end
  scene:play(hide,0.2)
 end
 scene:fade_in(focus[i],{duration=0.08})
 scene:play({{target=rows[i],opacity=1},{target=glyphs[i],opacity=1}},0.16)
 scene:create(lines[i],s.len>1 and 0.5 or 0.16)
 scene:fade_out(focus[i],{duration=0.08})
end
scene:wait(2.5)
return scene
`;
const surface=`-- Beats: fetch span -> calculate dst address -> choose coverage branch -> write len
-- elements in that row -> advance span pointer. Unaddressed cells/padding persist.
local rows=spanTable(false)
local bx,by,cell=1340,400,52
label(scene,"surface","SwSurface",bx,100,34)
label(scene,"dimensions","w = "..trace.w.."   h = "..trace.h.."   stride = "..trace.stride,bx,175,26)
label(scene,"alias","data / buf32",bx,240,26)
label(scene,"padding","padding",bx+trace.w*cell+10,305,23)
for x=0,trace.stride-1 do label(scene,"col_"..x,tostring(x),bx+x*cell+15,350,18) end
local pixels={}
for y=0,trace.h-1 do
 label(scene,"row_"..y,tostring(y*trace.stride),bx-70,by+(y+.5)*cell,19)
 for x=0,trace.stride-1 do
  local at=y*trace.stride+x;local px,py=bx+(x+.5)*cell,by+(y+.5)*cell
  pixels[at+1]=rect(scene,"memory_"..at,px,py,cell-2,cell-2,rgb(trace.background),"#cbd4de",20)
  if x>=trace.w then
   scene:line{id="padding_"..at,from=p(px-17,py-17),to=p(px-5,py-5),stroke="#8a96a4",width=1.5,layer=30}
  end
 end
end
label(scene,"address_rule","buf32[y * stride + x]",bx,920,28)
local events={}
for i,s in ipairs(trace.spans) do
 local g=scene:group{id="operation_"..i,opacity=0}
 rect(g,"array_cursor_"..i,510,tableTop+((i-1)%pageSize)*rowH,820,rowH-1,"#00000000","#ce8c31",40)
 rect(g,"memory_cursor_"..i,bx+(s.x+s.len/2)*cell,by+(s.y+.5)*cell,s.len*cell-4,cell-4,"#00000000","#ce8c31",40)
 label(g,"offset_"..i,s.y.." * "..trace.stride.." + "..s.x.." = "..s.offset,bx,985,28)
 label(g,"branch_"..i,s.coverage==255 and "255 : rasterPixel32" or (s.coverage.." : ALPHA_BLEND"),bx,1050,26)
 label(g,"range_"..i,"buf32["..s.offset.." .. "..(s.offset+s.len-1).."]",bx,1110,25)
 local names={"color","dst","out"}
 local values={trace.color,trace.background,s.writes[1]}
 for j,v in ipairs(values) do
  local px=bx+(j-1)*285
  label(g,"chipname_"..i.."_"..j,names[j],px,1200,21)
  rect(g,"chip_"..i.."_"..j,px+24,1260,44,44,rgb(v),"#cbd4de",30)
  label(g,"hex_"..i.."_"..j,string.format("%08X",v),px+58,1260,18)
 end
 events[i]=g
end
scene:wait(0.6)
for i,s in ipairs(trace.spans) do
 if i>1 and (i-1)%pageSize==0 then
  local hide,show={},{}
  for j=i-pageSize,i-1 do hide[#hide+1]={target=rows[j],opacity=0} end
  for j=i,math.min(i+pageSize-1,#rows) do show[#show+1]={target=rows[j],opacity=1} end
  scene:play(hide,0.1);scene:play(show,0.1)
 end
 scene:fade(events[i],1,0.12)
 scene:wait(s.coverage==255 and 0.55 or 0.22)
 local writes={}
 for j,v in ipairs(s.writes) do writes[#writes+1]={target=pixels[s.offset+j],fill=rgb(v)} end
 scene:play(writes,0.18)
 scene:wait(s.coverage==255 and 0.35 or 0.15)
 scene:fade(events[i],0,0.1)
end
scene:wait(2.5)
return scene
`;
const overview=`-- Beats: target binding -> actual path API calls -> add -> update/Prepare
-- -> ordered span reads and direct buffer writes -> sync. No intermediate bitmap.
-- The same actual engine trace drives all three views; cameras remain fixed.
local ax,rx,bx,top,cell=100,860,1620,520,40
label(scene,"api_heading","Shape / Canvas",ax,100,32)
label(scene,"rle_heading","SwRle",rx,100,32)
label(scene,"surface_heading","SwSurface",bx,100,32)
label(scene,"path","RenderShape.path",ax,420,26)
label(scene,"prepare_path","SwOutline → SwRle",rx,420,25)
label(scene,"dimensions","w="..trace.w.."  h="..trace.h.."  stride="..trace.stride,bx,420,24)
label(scene,"colorspace","cs = ABGR8888",bx,350,24)
local spanCount=label(scene,"span_count",#trace.spans.." spans",rx,930,27)
label(scene,"memory_rule","buf32[y * stride + x]",bx,930,24)
local function grid(id,x,cols)
 for c=0,cols do scene:line{id=id.."_x_"..c,from=p(x+c*cell,top),to=p(x+c*cell,top+trace.h*cell),stroke="#e2e7ed",width=1,layer=10} end
 for y=0,trace.h do scene:line{id=id.."_y_"..y,from=p(x,top+y*cell),to=p(x+cols*cell,top+y*cell),stroke="#e2e7ed",width=1,layer=10} end
end
grid("api_grid",ax,trace.w)
local buffer={}
for y=0,trace.h-1 do for x=0,trace.stride-1 do
 local index=y*trace.stride+x;local px,py=bx+(x+.5)*cell,top+(y+.5)*cell
 buffer[index+1]=rect(scene,"memory_"..index,px,py,cell-2,cell-2,rgb(trace.background),"#cbd4de",20)
 if x>=trace.w then scene:line{id="padding_"..index,from=p(px-13,py-13),to=p(px-5,py-5),stroke="#8a96a4",width=1.5,layer=30} end
end end
label(scene,"padding","padding",bx+trace.w*cell,480,20)
local targetFrame=rect(scene,"target_frame",bx+trace.stride*cell/2,top+trace.h*cell/2,trace.stride*cell+10,trace.h*cell+10,"#00000000","#ce8c31",40)
local sceneFrame=rect(scene,"root_scene",ax+trace.w*cell/2,top+trace.h*cell/2,trace.w*cell+20,trace.h*cell+20,"#00000000","#7199c8",40)
local polygon={}
for _,v in ipairs(trace.polygon) do polygon[#polygon+1]=p(ax+v[1]*cell,top+v[2]*cell) end
local retained=scene:polygon{id="retained_fill",points=polygon,fill=rgb(trace.color),stroke="#00000000",layer=20}
local edges,vertices={},{ }
for i,v in ipairs(polygon) do
 vertices[i]=scene:circle{id="vertex_"..i,center=v,radius=4,fill="#2078dc",layer=32}
 local previous=polygon[i==1 and #polygon or i-1]
 edges[i]=scene:line{id="edge_"..i,from=previous,to=v,stroke="#2078dc",width=3,layer=31}
end
local function call(id,value)
 local g=scene:group{id="api_"..id,opacity=0};label(g,"call_"..id,value,ax,240,25);return g
end
local calls={target=call("target","target(buffer,16,12,8,cs)"),fill=call("fill","fill(32,120,220,255)"),add=call("add","add(shape)"),update=call("update","update()"),draw=call("draw","draw(false)"),sync=call("sync","sync()"),close=call("close","close()")}
local pathCalls={}
for i,v in ipairs(trace.polygon) do pathCalls[i]=call("path_"..i,(i==1 and "moveTo(" or "lineTo(")..v[1]..","..v[2]..")") end
local prepare=scene:group{id="prepare_label",opacity=0}
label(prepare,"prepare_call","shapeGenRle()",rx,240,26)
local draw=scene:group{id="draw_label",opacity=0}
label(draw,"render_call","rasterShape()",bx,240,26)
local rleRows,rleLines={},{}
for y=0,trace.h-1 do rleRows[y+1]=scene:group{id="rle_row_"..y,opacity=0};rleLines[y+1]={} end
local operations={}
for i,s in ipairs(trace.spans) do
 local line=spanGlyph(rleRows[s.y+1],"span_"..i,s,rx,top,cell)
 rleLines[s.y+1][#rleLines[s.y+1]+1]=line
 local g=scene:group{id="operation_"..i,opacity=0}
 rect(g,"read_begin_"..i,rx+(s.x+.5)*cell,top+(s.y+.5)*cell,22,22,"#00000000","#ce8c31",40)
 g:line{id="read_len_"..i,from=p(rx+(s.x+.5)*cell,top+(s.y+.5)*cell),to=p(rx+(s.x+s.len+.5)*cell,top+(s.y+.5)*cell),stroke="#ce8c31",width=3,layer=40}
 rect(g,"write_range_"..i,bx+(s.x+s.len/2)*cell,top+(s.y+.5)*cell,s.len*cell-4,cell-4,"#00000000","#ce8c31",40)
 label(g,"span_xy_"..i,"x="..s.x.."  y="..s.y.."  len="..s.len,rx,1040,25)
 label(g,"coverage_"..i,"coverage="..s.coverage,rx,1100,25)
 label(g,"offset_"..i,s.y.." * "..trace.stride.." + "..s.x.." = "..s.offset,bx,1040,25)
 label(g,"range_"..i,"buf32["..s.offset..".."..(s.offset+s.len-1).."]",bx,1100,25)
 operations[i]=g
end
-- This is a pedagogical replay of API order and completed Prepare/draw results.
-- Worker scheduling is not asserted by this timeline; evidence build has no workers.
local active
local function showCall(g)
 if active then scene:fade(active,0,0.12) end
 scene:fade(g,1,0.12);active=g
end
showCall(calls.target)
scene:fade_in(targetFrame,{duration=0.3});scene:wait(0.5);scene:fade_out(targetFrame,{duration=0.2})
for i=1,#polygon do
 showCall(pathCalls[i])
 if i>1 then scene:create(edges[i],0.65) end
 scene:fade_in(vertices[i],{duration=0.15});scene:wait(0.35)
end
showCall(calls.close);scene:create(edges[1],0.65)
showCall(calls.fill);scene:fade_in(retained,{duration=0.45});scene:wait(0.4)
showCall(calls.add);scene:fade_in(sceneFrame,{duration=0.3});scene:wait(0.45)
showCall(calls.update);scene:fade(prepare,1,0.2)
for row=1,trace.h do
 scene:fade(rleRows[row],1,0.15)
 if #rleLines[row]>0 then scene:create(rleLines[row],0.25) end
end
scene:fade_in(spanCount,{duration=0.15})
scene:wait(0.7)
showCall(calls.draw);scene:fade(draw,1,0.2)
for i,s in ipairs(trace.spans) do
 scene:fade(operations[i],1,0.1)
 scene:wait(s.coverage==255 and 0.4 or 0.2)
 local writes={};for j,v in ipairs(s.writes) do writes[#writes+1]={target=buffer[s.offset+j],fill=rgb(v)} end
 scene:play(writes,0.2)
 scene:wait(s.coverage==255 and 0.3 or 0.12)
 scene:fade(operations[i],0,0.1)
end
showCall(calls.sync);scene:wait(2.5)
return scene
`;
